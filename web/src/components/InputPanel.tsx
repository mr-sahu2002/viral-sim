import { useRef, useState } from 'react';
import { fileToImage } from '../api';
import type { Platform } from '../types';

export interface FormState {
  platform: Platform;
  text: string;
  image?: { mimeType: string; data: string; url: string };
  audience: string;
  population: number;
  seeds: number;
}

const PLATFORMS: { id: Platform; label: string; limit: number }[] = [
  { id: 'linkedin', label: 'LinkedIn', limit: 3000 },
  { id: 'x', label: 'X', limit: 280 },
  { id: 'instagram', label: 'Instagram', limit: 2200 },
];

export default function InputPanel(props: {
  form: FormState;
  setForm: (fn: (f: FormState) => FormState) => void;
  running: boolean;
  status: string;
  onRun: () => void;
}) {
  const { form, setForm, running, status, onRun } = props;
  const fileRef = useRef<HTMLInputElement>(null);
  const [drag, setDrag] = useState(false);
  const set = <K extends keyof FormState>(k: K, v: FormState[K]) => setForm((f) => ({ ...f, [k]: v }));
  const limit = PLATFORMS.find((p) => p.id === form.platform)!.limit;

  async function onFile(file?: File) {
    if (!file || !file.type.startsWith('image/')) return;
    set('image', await fileToImage(file));
  }

  return (
    <div className="card input-grid">
      <div className="cell post-cell">
        <div className="row between">
          <label className="mono label">Post</label>
          <div className="tabs">
            {PLATFORMS.map((p) => (
              <button key={p.id} className={form.platform === p.id ? 'tab active' : 'tab'} onClick={() => set('platform', p.id)} disabled={running}>
                {p.label}
              </button>
            ))}
          </div>
        </div>
        <textarea
          value={form.text}
          onChange={(e) => set('text', e.target.value)}
          placeholder="Paste your post copy here…"
          rows={6}
          disabled={running}
        />
        <div className="row between">
          <span className={`mono small ${form.text.length > limit ? 'warn' : 'muted'}`}>
            {form.text.length}/{limit}
          </span>
        </div>
        <div
          className={`drop ${drag ? 'drag' : ''}`}
          onClick={() => fileRef.current?.click()}
          onDragOver={(e) => (e.preventDefault(), setDrag(true))}
          onDragLeave={() => setDrag(false)}
          onDrop={(e) => (e.preventDefault(), setDrag(false), onFile(e.dataTransfer.files[0]))}
        >
          {form.image ? (
            <div className="row gap">
              <img src={form.image.url} alt="" className="thumb" />
              <span className="mono small">image attached — click or drop to replace</span>
              <button className="link" onClick={(e) => (e.stopPropagation(), set('image', undefined))}>
                remove
              </button>
            </div>
          ) : (
            <span className="mono small muted">IMAGE (optional) — click or drop</span>
          )}
          <input ref={fileRef} type="file" accept="image/*" hidden onChange={(e) => onFile(e.target.files?.[0])} />
        </div>
      </div>

      <div className="cell">
        <label className="mono label">Target demographic</label>
        <textarea className="bare" value={form.audience} onChange={(e) => set('audience', e.target.value)} rows={5} disabled={running} />
      </div>

      <div className="cell">
        <label className="mono label">Population</label>
        <select value={form.population} onChange={(e) => set('population', Number(e.target.value))} disabled={running}>
          {[25, 50, 100, 150, 200].map((n) => (
            <option key={n} value={n}>
              {n} agents
            </option>
          ))}
        </select>
        <p className="mono tiny muted">~75% personas in-target, 25% outside, generated by Gemini per audience</p>
        <div className="row between" style={{ marginTop: 14 }}>
          <label className="mono label">Boost</label>
          <span className="mono small">{form.seeds} seeds</span>
        </div>
        <input type="range" min={1} max={20} value={form.seeds} onChange={(e) => set('seeds', Number(e.target.value))} disabled={running} />
        <p className="mono tiny muted">round-1 initial reach</p>
      </div>

      <button className={`run ${running ? 'running' : ''}`} onClick={onRun} disabled={running}>
        {running ? (
          <>
            RUNNING…
            <span className="tiny">{status}</span>
          </>
        ) : (
          'RUN'
        )}
      </button>
    </div>
  );
}
